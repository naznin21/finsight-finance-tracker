import { useEffect, useState } from 'react'
import { getInsights } from '../services/api'
import Layout from '../components/Layout'
import { Lightbulb, AlertTriangle, BarChart3 } from 'lucide-react'

export default function InsightsPage() {
  const [insights, setInsights] = useState(null)

  useEffect(() => { getInsights().then(r => setInsights(r.data)) }, [])

  return (
    <Layout title="AI Insights" subtitle="Personalized recommendations generated by AI">
      {!insights ? (
        <p className="text-center text-muted py-10">Loading insights...</p>
      ) : (
        <>
          {/* Suggestions */}
          <div className="card">
            <h2 className="font-semibold mb-3 text-accent flex items-center gap-2">
              <Lightbulb size={16} /> Personalized Suggestions
            </h2>
            <ul className="space-y-2">
              {insights.suggestions.map((s, i) => (
                <li key={i} className="text-sm text-slate-300 flex gap-2">
                  <span className="text-accent">→</span> {s}
                </li>
              ))}
              {insights.suggestions.length === 0 && (
                <p className="text-muted text-sm">Not enough data yet.</p>
              )}
            </ul>
          </div>

          {/* Anomalies */}
          {insights.anomalies.length > 0 && (
            <div className="card">
              <h2 className="font-semibold mb-3 text-expense flex items-center gap-2">
                <AlertTriangle size={16} /> Anomaly Detection
              </h2>
              <ul className="space-y-2">
                {insights.anomalies.map((a, i) => (
                  <li key={i} className="text-sm text-expense">{a}</li>
                ))}
              </ul>
            </div>
          )}

          {/* Spending Patterns */}
          <div className="card">
            <h2 className="font-semibold mb-3 text-slate-100 flex items-center gap-2">
              <BarChart3 size={16} className="text-accent" /> Spending Patterns (3-month avg)
            </h2>
            <div className="space-y-2">
              {Object.entries(insights.spendingPatterns).map(([cat, avg]) => (
                <div key={cat} className="flex justify-between text-sm">
                  <span className="text-slate-300">{cat}</span>
                  <span className="font-medium text-slate-100">₹{Number(avg).toFixed(2)} / transaction</span>
                </div>
              ))}
              {Object.keys(insights.spendingPatterns).length === 0 && (
                <p className="text-muted text-sm">Not enough data yet.</p>
              )}
            </div>
          </div>
        </>
      )}
    </Layout>
  )
}
